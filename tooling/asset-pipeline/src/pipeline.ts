import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { z } from 'zod';
import {
  AssetEntrySchema,
  AssetManifestSchema,
  ContentIdSchema,
  NfcTextSchema,
  type AssetEntry,
  type AssetManifest,
} from '@huroofi/content-schema';

/**
 * Builds the pack asset manifest (plan §4 asset contract, §3.3 SHA-256 manifests) from
 * files plus hand-written sidecars. Licensing and duration come from the sidecar on purpose:
 * provenance must be declared by a person, never guessed by tooling.
 */

const MIME_BY_EXT: Record<string, AssetEntry['mime']> = {
  '.m4a': 'audio/mp4',
  '.mp4': 'audio/mp4',
  '.aac': 'audio/aac',
  '.mp3': 'audio/mpeg',
  '.ogg': 'audio/ogg',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
};

const SidecarSchema = z.object({
  assetId: ContentIdSchema,
  license: z.string().min(1),
  credit: z.string().min(1),
  transcript: NfcTextSchema.optional(),
  durationMs: z.number().int().positive().optional(),
});

export interface BuildResult {
  manifest: AssetManifest;
  errors: string[];
}

const SIDECAR = '.meta.json';
const IGNORED = new Set(['README.md', '.DS_Store', '.gitkeep']);

function* files(dir: string): Generator<string> {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (!IGNORED.has(name)) yield path;
  }
}

export function buildManifest(
  assetsDir: string,
  pack: { packId: string; contentVersion: string; locale: string },
): BuildResult {
  const errors: string[] = [];
  const assets: AssetEntry[] = [];
  const all = [...files(assetsDir)];
  const sidecars = new Set(all.filter((f) => f.endsWith(SIDECAR)));

  for (const file of all) {
    if (file.endsWith(SIDECAR)) {
      if (!all.includes(file.slice(0, -SIDECAR.length))) {
        errors.push(`${rel(assetsDir, file)}: sidecar has no matching asset file`);
      }
      continue;
    }
    const relativePath = rel(assetsDir, file);
    const ext = relativePath.slice(relativePath.lastIndexOf('.')).toLowerCase();
    const mime = MIME_BY_EXT[ext];
    if (!mime) {
      errors.push(`${relativePath}: unsupported file type ${ext}`);
      continue;
    }
    if (!sidecars.has(file + SIDECAR)) {
      errors.push(`${relativePath}: missing ${SIDECAR} sidecar (license, credit, assetId)`);
      continue;
    }
    let sidecarRaw: unknown;
    try {
      sidecarRaw = JSON.parse(readFileSync(file + SIDECAR, 'utf8'));
    } catch (e) {
      errors.push(`${relativePath}${SIDECAR}: invalid JSON (${(e as Error).message})`);
      continue;
    }
    const sidecar = SidecarSchema.safeParse(sidecarRaw);
    if (!sidecar.success) {
      errors.push(
        `${relativePath}${SIDECAR}: ${sidecar.error.issues.map((i) => `${i.path.join('.')} ${i.message}`).join('; ')}`,
      );
      continue;
    }
    const bytes = readFileSync(file);
    const entry = AssetEntrySchema.safeParse({
      assetId: sidecar.data.assetId,
      locale: pack.locale,
      contentVersion: pack.contentVersion,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      mime,
      sizeBytes: bytes.length,
      ...(sidecar.data.durationMs !== undefined && { durationMs: sidecar.data.durationMs }),
      license: sidecar.data.license,
      credit: sidecar.data.credit,
      ...(sidecar.data.transcript !== undefined && { transcript: sidecar.data.transcript }),
      relativePath,
    });
    if (!entry.success) {
      errors.push(
        `${relativePath}: ${entry.error.issues.map((i) => `${i.path.join('.')} ${i.message}`).join('; ')}`,
      );
      continue;
    }
    assets.push(entry.data);
  }

  const seen = new Map<string, string>();
  for (const a of assets) {
    const prev = seen.get(a.assetId);
    if (prev) errors.push(`duplicate assetId ${a.assetId} in ${prev} and ${a.relativePath}`);
    seen.set(a.assetId, a.relativePath);
  }

  const manifest = AssetManifestSchema.parse({
    packId: pack.packId,
    contentVersion: pack.contentVersion,
    assets: assets.sort((x, y) => x.assetId.localeCompare(y.assetId)),
  });
  return { manifest, errors };
}

/**
 * Metro can only bundle files referenced by static `require` calls, so the app gets a
 * generated module mapping audio asset ids to bundled sources.
 */
export function renderAudioSourcesModule(
  manifest: AssetManifest,
  assetsDirFromModule: string,
): string {
  const lines = manifest.assets
    .filter((a) => a.mime.startsWith('audio/'))
    .map(
      (a) =>
        `  ${JSON.stringify(a.assetId)}: require(${JSON.stringify(`${assetsDirFromModule}/${a.relativePath}`)}),`,
    );
  return [
    '// GENERATED by tooling/asset-pipeline (`pnpm assets:build`). Do not edit by hand.',
    '/* eslint-disable @typescript-eslint/no-require-imports */',
    `export const AUDIO_SOURCES: Readonly<Record<string, number>> = {`,
    ...lines,
    '};',
    '',
  ].join('\n');
}

export function renderManifestJson(manifest: AssetManifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

const rel = (root: string, path: string) => relative(root, path).split(sep).join('/');
